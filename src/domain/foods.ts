import type { Food, FoodCategory } from './nutrition';

/**
 * Table d'aliments : kcal pour 100 g, d'après les tables nutritionnelles usuelles (valeurs indicatives,
 * arrondies). `cuit` quand la cuisson change la valeur ; `portion` = portion type, proposée par défaut.
 */
type Row = [id: string, name: string, cru: number, cuit?: number | null, portion?: [label: string, grams: number]];

function group(category: FoodCategory, rows: Row[]): Food[] {
  return rows.map(([id, name, cru, cuit, portion]) => ({
    id,
    name,
    category,
    cru,
    ...(cuit != null ? { cuit } : {}),
    ...(portion ? { portion: { label: portion[0], grams: portion[1] } } : {}),
  }));
}

