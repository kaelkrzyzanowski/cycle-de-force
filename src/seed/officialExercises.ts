import { slugify } from '../domain/ids';
import type { Exercise, ExerciseCategory, Lift } from '../domain/types';

type Row = [name: string, aliases?: string[], lift?: Lift];

function group(category: ExerciseCategory, rows: Row[]): Exercise[] {
  return rows.map(([name, aliases = [], lift]) => ({
    id: slugify(name),
    name,
    aliases,
    category,
    ...(lift ? { defaultLift: lift } : {}),
  }));
}

